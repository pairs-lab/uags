import datetime as dt
JP={dt.date(2026,10,12),dt.date(2026,11,3),dt.date(2026,11,23)}
def wd(a,b,hol=JP):
    d=a;n=0
    while d<=b:
        if d.weekday()<5 and d not in hol: n+=1
        d+=dt.timedelta(1)
    return n
D=dt.date
weeks=[("W1",D(2026,9,29),D(2026,10,4)),("W2",D(2026,10,5),D(2026,10,11)),("W3",D(2026,10,12),D(2026,10,18)),
("W4",D(2026,10,19),D(2026,10,25)),("W5",D(2026,10,26),D(2026,11,1)),("W6",D(2026,11,2),D(2026,11,8)),
("W7",D(2026,11,9),D(2026,11,15)),("W8",D(2026,11,16),D(2026,11,22)),("W9",D(2026,11,23),D(2026,11,29))]
for w,a,b in weeks: print(w,a,b,"workdays JP:",wd(a,b),"no-hol:",wd(a,b,set()))
for end in [D(2026,11,13),D(2026,11,26),D(2026,11,27)]:
    print("Sep29..",end,"JP:",wd(D(2026,9,29),end),"no-hol:",wd(D(2026,9,29),end,set()))
for d in [D(2026,10,2),D(2026,10,9),D(2026,10,12),D(2026,10,14),D(2026,10,16),D(2026,10,23),D(2026,10,30),D(2026,11,3),D(2026,11,6),D(2026,11,13),D(2026,11,20),D(2026,11,23),D(2026,11,25),D(2026,11,27)]:
    print(d,d.strftime('%a'))
