# ------------------------------------------------------------------------------ basics
def num(x):
    """A JSON number as a float: None and the strings "nan"/"inf" (usplat.runlog) included."""
    if x is None:
        return float("nan")
    return float(x)


def finite(x):
    return x is not None and math.isfinite(float(x))


def sha256_file(path):
    with open(path, "rb") as f:
        return hashlib.sha256(f.read()).hexdigest()


def load_record(path):
    """The metrics body of a usplat.runlog record (eval_seg.py, eval_change_nor.py, merges)."""
    if not os.path.exists(path):
        raise SystemExit(f"{short(path)}: no such file")
    with open(path) as f:
        d = json.load(f)
    if d.get("status", "ok") != "ok":
        raise SystemExit(f"{short(path)}: status {d.get('status')!r}, not a finished run")
    return d["metrics"] if isinstance(d.get("metrics"), dict) else d


def short(path):
    """A path for the outputs: $RES/..., $NORD/..., repo-relative, or ~/... (no user name)."""
    p = os.path.abspath(path)
    for name, base in (("$RES", RES), ("$NORD", NORD)):
        if p == base or p.startswith(base + os.sep):
            return name + p[len(base):]
    if p == ROOT:
        return "."
    if p.startswith(ROOT + os.sep):
        return os.path.relpath(p, ROOT)
    home = os.path.expanduser("~")
    if p.startswith(home + os.sep):
        return "~" + p[len(home):]
    return p


def command_line(argv):
    """The generating command with abbreviated paths (first line of every output)."""
    out = ["python3", "scripts/quant_stats.py"]
    for a in argv:
        if os.path.sep in a and os.path.exists(a.split("=")[-1]):
            a = short(a)
        out.append(shlex.quote(a) if not a.startswith("$") else a)
    return " ".join(out)


def source(path):
    return dict(path=short(path), sha256=sha256_file(path))


# ------------------------------------------------------------------------------ statistics
def sign_test(diffs):
    """Exact two-sided sign test of paired differences, ties (exactly 0) dropped:
    p = min(1, 2 min(P[K <= k], P[K >= k])), K ~ Binomial(n, 1/2), k = #positive."""
    d = [float(x) for x in diffs]
    nz = [x for x in d if x != 0.0]
    n, k = len(nz), sum(1 for x in nz if x > 0)
    if n == 0:
        return dict(n=0, k=0, ties=len(d), p=float("nan"))
    p = min(1.0, 2.0 * min(stats.binom.cdf(k, n, 0.5), stats.binom.sf(k - 1, n, 0.5)))
    return dict(n=n, k=k, ties=len(d) - n, p=float(p))


def holm(ps):
    """Holm step-down adjusted p-values (monotone, capped at 1), in the input order."""
    if any(not math.isfinite(p) for p in ps):
        raise SystemExit("holm: a test of the family has no p-value")
    m = len(ps)
    order = sorted(range(m), key=lambda i: ps[i])
    adj, run = [0.0] * m, 0.0
    for r, i in enumerate(order):
        run = max(run, min(1.0, (m - r) * ps[i]))
        adj[i] = run
    return adj


def wilcoxon_p(diffs):
    """Wilcoxon signed-rank p (zeros dropped; scipy's method 'auto': exact for n <= 50
    without zeros), the secondary column of F1."""
    d = np.asarray([x for x in diffs if x != 0.0], float)
    if d.size == 0:
        return float("nan")
    return float(stats.wilcoxon(d, zero_method="wilcox", method="auto").pvalue)


def boot_mean_ci(diffs, B=BOOT_B, seed=BOOT_SEED):
    """Percentile 95% CI of the mean paired difference over scene resamples (descriptive)."""
    d = np.asarray(diffs, float)
    rng = np.random.default_rng(seed)
    mb = d[rng.integers(0, d.size, size=(B, d.size))].mean(1)
    lo, hi = np.percentile(mb, [2.5, 97.5])
    return [float(lo), float(hi)]


def summarize(diffs, n_scenes=None, boot=True):
    """x/N, ties, median and mean difference, sign p (and the bootstrap CI) of signed diffs
    (positive = first row better)."""
    d = [float(x) for x in diffs]
    st = sign_test(d)
    out = dict(n=len(d) if n_scenes is None else n_scenes, wins=sum(1 for x in d if x > 0),
               ties=st["ties"], losses=sum(1 for x in d if x < 0),
               median_diff=float(np.median(d)), mean_diff=float(np.mean(d)), sign_p=st["p"])
    if boot:
        out["boot95_mean_diff"] = boot_mean_ci(d)
    return out


def pstd(v):
    """Population std (usplat.seg_eval.scene_stats)."""
    return float(np.std(np.asarray(v, float)))


# ------------------------------------------------------------------------------ LaTeX cells
def fmt(v, spec):
    """One printed cell value. spec: a format spec ('.1f', '+.2f', 'd'), 'p' (p-value), or
    's' / 'tex' (an identifier from the JSON: verbatim / with '_' escaped)."""
    if v is None or (isinstance(v, float) and not math.isfinite(v)):
        return "--"
    if spec == "d":
        return str(int(v))
    if spec == "s":                               # an identifier stored in the JSON
        return str(v)
    if spec == "tex":                             # the same, LaTeX-escaped
        return str(v).replace("_", "\\_")
    if spec == "p":
        s = format(float(v), ".2g")
        if "e" in s:
            m, e = s.split("e")
            s = f"${m}\\times10^{{{int(e)}}}$"
        return s
    s = format(float(v), spec)
    if float(s.replace("+", "")) == 0.0:          # no signed zero
        s = s.lstrip("+-")
    return s


def get_key(obj, key):
    """The value at a '/'-separated key (list indices as integers)."""
    cur = obj
    for part in key.split("/"):
        cur = cur[int(part)] if isinstance(cur, list) else cur[part]
    return cur


def render(template, values, specs):
    return re.sub(r"@(\d+)", lambda m: fmt(values[int(m.group(1))], specs[int(m.group(1))]),
                  template)


class Tex:
    """LaTeX rows in blocks; every number cell keeps the JSON keys it is printed from."""

    def __init__(self, command):
        self.command = command
        self.blocks = []

    def block(self, name, note):
        b = dict(name=name, note=note, rows=[])
        self.blocks.append(b)
        return b

    @staticmethod
    def label(text):
        return dict(text=text, keys=[], template=text, specs=[])

    @staticmethod
    def cell(keys, specs, template=None):
        keys = [keys] if isinstance(keys, str) else list(keys)
        specs = [specs] * len(keys) if isinstance(specs, str) else list(specs)
        return dict(keys=keys, specs=specs, template=template or "@0")

    @staticmethod
    def rule(b, text="\\midrule"):
        b["rows"].append(dict(line=text))

    def finish(self, data):
        """Fill each cell's text from `data` (the JSON body) and return the .tex text."""
        lines = [f"%% generated by: {self.command}"]
        for b in self.blocks:
            lines.append(f"%% block: {b['name']} -- {b['note']}")
            for r in b["rows"]:
                if "line" in r:
                    lines.append(r["line"])
                    continue
                for c in r["cells"]:
                    if c["keys"]:
                        c["text"] = render(c["template"], [get_key(data, k) for k in c["keys"]],
                                           c["specs"])
                lines.append(" & ".join(c["text"] for c in r["cells"]) + "\\\\")
            lines.append("")
        return "\n".join(lines)


def row(b, cells):
    b["rows"].append(dict(cells=cells))


def mean_std_cell(key, spec):
    return Tex.cell([f"{key}/mean", f"{key}/std"], spec, "@0{\\scriptsize$\\,\\pm\\,$@1}")


def write_outputs(args, data, tex):
    os.makedirs(os.path.dirname(os.path.abspath(args.json)), exist_ok=True)
    text = tex.finish(data)
    data["latex"] = dict(file=os.path.basename(args.tex), blocks=tex.blocks)
    with open(args.tex, "w") as f:
        f.write(text)
    with open(args.json, "w") as f:
        json.dump(data, f, indent=1, allow_nan=True)
        f.write("\n")
    print(f"wrote {short(args.json)} and {short(args.tex)}")


