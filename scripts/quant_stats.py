P2_SYMBOLS = (("beta0", "beta_0"), ("a", "gamma_e"), ("b", "gamma_a"), ("g", "gamma_u"))


def betas(args, argv):
    data, tex = header(args, argv)
    labels = args.labels.split(",")
    if len(labels) != len(args.val):
        raise SystemExit("--labels needs one name per --val file")
    data["formula"] = ("beta_p = beta_0 exp(-gamma_e u_epi - gamma_a u_ale - gamma_u 1[u_ale "
                       "undefined]) (usplat/predictive.py adaptive_beta; code a, b, g = gamma_e, "
                       "gamma_a, gamma_u); fitted by NLL on the validation split")
    data["datasets"] = []
    for name, path in zip(labels, args.val):
        m = load_record(path)
        e = dict(dataset=name, source=source(path), scenes=list(m["scenes"]))
        for row_, key in (("ours_P2", "P2"), ("ours_P2p1", "P2p1")):
            bb = m["betas"].get(row_)
            if isinstance(bb, dict):
                e[key] = {sym: float(bb[c]) for c, sym in P2_SYMBOLS}
        e["P0_beta"] = float(m["betas"]["ours_P0"])
        e["averaging_beta"] = float(m["betas"]["averaging"])
        data["datasets"].append(e)
    if args.test:
        for e, path in zip(data["datasets"], args.test):
            t = load_record(path)["betas"]["ours_P2"]
            e["test_record_uses_same_P2"] = all(abs(float(t[c]) - e["P2"][s]) < 1e-12
                                                for c, s in P2_SYMBOLS)
    b = tex.block("p2_coefficients", "Fitted P2 coefficients (validation NLL). Cols: dataset | "
                  "$\\beta_0$ | $\\gamma_e$ | $\\gamma_a$ | $\\gamma_u$ | $\\beta$ of P0")
    for i, e in enumerate(data["datasets"]):
        k = f"datasets/{i}"
        row(b, [Tex.cell(f"{k}/dataset", "s"), Tex.cell(f"{k}/P2/beta_0", ".1f"),
                Tex.cell(f"{k}/P2/gamma_e", "+.2f"), Tex.cell(f"{k}/P2/gamma_a", "+.2f"),
                Tex.cell(f"{k}/P2/gamma_u", "+.3f"), Tex.cell(f"{k}/P0_beta", ".1f")])
    write_outputs(args, data, tex)


