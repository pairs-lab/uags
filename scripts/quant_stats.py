# ------------------------------------------------------------------------------ Table I (seg)
def seg_values(m, row, key, variant="all"):
    """{scene: value} of metrics.scenes[s].rows[row][variant][key] (key 'ause:<signal>' reads
    the ranking signal's AUSE)."""
    out = {}
    for s, sc in m["scenes"].items():
        r = sc["rows"].get(row)
        if r is None:
            raise SystemExit(f"row {row!r} missing in scene {s}")
        r = r[variant]
        out[s] = num(r["ranking"][key[5:]]["ause"]) if key.startswith("ause:") else num(r[key])
    return out


def signed(a, b, key):
    """Per-scene signed differences in display units, positive = a better."""
    sc = SCALE[key.split(":")[0]]
    if list(a) != list(b):
        raise SystemExit("rows differ in scenes")
    if HIGHER[key.split(":")[0]]:
        return {s: sc * (a[s] - b[s]) for s in a}
    return {s: sc * (b[s] - a[s]) for s in a}


def bins_ece(rel):
    """ECE from one set of reliability bins (count, conf, acc; NaN in empty bins)."""
    c = np.asarray(rel["count"], float)
    cf = np.nan_to_num(np.asarray([num(x) for x in rel["conf"]], float))
    ac = np.nan_to_num(np.asarray([num(x) for x in rel["acc"]], float))
    return float(np.sum(c * np.abs(cf - ac)) / c.sum()) if c.sum() > 0 else float("nan")


def pool_bins(rels):
    """Bins summed over scenes: count, mean confidence and accuracy per bin."""
    C = SC = SA = 0.0
    for rel in rels:
        c = np.asarray(rel["count"], float)
        C = C + c
        SC = SC + c * np.nan_to_num(np.asarray([num(x) for x in rel["conf"]], float))
        SA = SA + c * np.nan_to_num(np.asarray([num(x) for x in rel["acc"]], float))
    ok = C > 0
    conf = np.where(ok, SC / np.maximum(C, 1), np.nan)
    acc = np.where(ok, SA / np.maximum(C, 1), np.nan)
    return dict(count=[int(x) for x in C], conf=[float(x) for x in conf],
                acc=[float(x) for x in acc])


def ece_check(m, tol=1e-12):
    """Max |ECE from bins - stored ECE| over every row, scene and variant of a record."""
    worst, n = 0.0, 0
    for s, sc in m["scenes"].items():
        for r, rr in sc["rows"].items():
            for var, v in rr.items():
                if not isinstance(v, dict) or "reliability" not in v:
                    continue
                e = abs(bins_ece(v["reliability"]) - num(v["ece"]))
                if sum(v["reliability"]["count"]) != int(v["n_pixels"]):
                    raise SystemExit(f"{s}/{r}/{var}: bin counts do not sum to n_pixels")
                worst, n = max(worst, e), n + 1
    if worst > tol:
        raise SystemExit(f"ECE recomputed from the bins differs from the stored ECE by {worst}")
    return dict(max_abs_err=worst, n_checked=n, tol=tol)


def check_prereg_f1(p):
    f1 = p["families"]["F1"]
    tests = [(t["baseline"], t["metric"]) for t in f1["tests"]]
    want = [(b, k) for b in F1_BASELINES for k in F1_METRICS]
    if tests != want or f1["ours_rows"] != F1_OURS:
        raise SystemExit("configs/quant_prereg.json: F1 differs from the family this script "
                         "implements; refusing")
    return f1


def choose_val(val_path, key):
    """A validation choice of make_tables.py (@legs, @css) from a validation record."""
    import make_tables as MT
    return MT.choose(MT.body(val_path)["summary"], key)


def seg(args, argv):
    prereg = json.load(open(args.prereg))
    f1 = check_prereg_f1(prereg)
    data, tex = header(args, argv)
    paths = {"replica": args.replica, "scannet": args.scannet}
    M = {d: load_record(p) for d, p in paths.items()}
    legs = dict(zip(DATASETS, args.legs.split(",")))
    for d in DATASETS:
        if legs[d] != f1["baselines"]["legs"][d]:
            raise SystemExit(f"--legs {legs[d]} for {d}: the prereg says {f1['baselines']['legs'][d]}")
    val = {d: getattr(args, f"{d}_val") or os.path.join(os.path.dirname(paths[d]), "eval_val.json")
           for d in DATASETS}
    css = {}
    for d in DATASETS:
        if os.path.exists(val[d]):
            ch = choose_val(val[d], "@legs")
            if ch != legs[d]:
                raise SystemExit(f"{d}: validation chooses {ch} for LEGaussians, not {legs[d]}")
            css[d] = choose_val(val[d], "@css")
        else:
            css[d] = "css"
    data["inputs"] = {d: dict(source(paths[d]), scenes=list(M[d]["scenes"]),
                              validation=(short(val[d]) if os.path.exists(val[d]) else None))
                      for d in DATASETS}
    data["prereg"] = source(args.prereg)
    data["rows"] = {d: dict(legs=legs[d], css=css[d]) for d in DATASETS}
    brow = lambda b, d: legs[d] if b == "legs" else b

    # ---- F1: 20 paired tests over the 14 scenes, Holm
    tests = []
    for t in f1["tests"]:
        b, key = t["baseline"], t["metric"]
        ours = F1_OURS[key]
        e = dict(id=t["id"], baseline=b, metric=key, ours=ours, unit=UNIT[key],
                 better="higher" if HIGHER[key] else "lower",
                 baseline_rows={d: brow(b, d) for d in DATASETS}, per_scene={}, means={})
        pooled = []
        for d in DATASETS:
            va, vb = seg_values(M[d], ours, key), seg_values(M[d], brow(b, d), key)
            diff = signed(va, vb, key)
            e["per_scene"][d] = diff
            e[d] = summarize(list(diff.values()))
            e["means"][d] = dict(ours=SCALE[key] * float(np.mean(list(va.values()))),
                                 baseline=SCALE[key] * float(np.mean(list(vb.values()))))
            pooled += list(diff.values())
        e["pooled"] = summarize(pooled)
        e["pooled"]["wilcoxon_p"] = wilcoxon_p(pooled)
        tests.append(e)
    adj = holm([e["pooled"]["sign_p"] for e in tests])
    for e, a in zip(tests, adj):
        e["pooled"]["holm_p"] = a
        e["pooled"]["significant"] = bool(a < prereg["significance"]["alpha"])
    data["f1"] = dict(family="F1", n_tests=len(tests), adjustment="holm",
                      alpha=prereg["significance"]["alpha"], label=f1["label"],
                      wilcoxon="scipy.stats.wilcoxon, zero_method wilcox, method auto",
                      bootstrap=dict(resamples=BOOT_B, seed=BOOT_SEED, of="mean paired difference"),
                      tests=tests)

    # ---- descriptive comparisons (not a declared family: unadjusted, never "significant")
    def comp(a_row, b, key, label):
        e = dict(label=label, first=a_row, baseline=b, metric=key, unit=UNIT[key])
        pooled = []
        for d in DATASETS:
            va, vb = seg_values(M[d], a_row, key), seg_values(M[d], brow(b, d), key)
            diff = signed(va, vb, key)
            e[d] = summarize(list(diff.values()), boot=False)
            pooled += list(diff.values())
        e["pooled"] = summarize(pooled, boot=False)
        return e
    desc = dict(note="descriptive: unadjusted sign tests, not a declared family (R1)")
    desc["p0_in_place_of_p2"] = [comp("ours_P0", b, k,
                                      f"ours_P0 vs {b} {k}")
                                 for b in F1_BASELINES for k in F1_METRICS]
    desc["averaging_vs_trained"] = [comp("averaging", b, k, f"averaging vs {b} {k}")
                                    for b in ("f3dgs", "legs") for k in F1_METRICS]
    desc["p2_vs_p0"] = [comp("ours_P2", "ours_P0", k, f"ours_P2 vs ours_P0 {k}")
                        for k in ("ece", "nll", "brier", "aurc")]
    data["descriptive"] = desc

    # ---- calibration: both aggregations, from the stored bins
    cal = dict(ece_bins_check={d: ece_check(M[d]) for d in DATASETS})
    cal_rows = {d: ["ours_P2", "ours_P0", "ours_P1", "averaging", "f3dgs", legs[d],
                    "2d_features", css[d]] for d in DATASETS}
    for d in DATASETS:
        cal[d] = {}
        for r in cal_rows[d]:
            alls = [sc["rows"][r]["all"] for sc in M[d]["scenes"].values()]
            n = np.asarray([float(a["n_pixels"]) for a in alls])
            w = lambda k: float(np.sum(n * np.asarray([num(a[k]) for a in alls])) / n.sum())
            sm = lambda k: float(np.mean([num(a[k]) for a in alls]))
            bins = pool_bins([a["reliability"] for a in alls])
            ece_pooled = bins_ece(bins)
            acc_bins = float(np.nansum(np.asarray(bins["count"]) * np.nan_to_num(bins["acc"]))
                             / np.sum(bins["count"]))
            if abs(acc_bins - w("acc")) > 1e-9:
                raise SystemExit(f"{d}/{r}: pooled accuracy from the bins differs from the "
                                 f"pixel-weighted accuracy")
            cal[d][r] = dict(
                ece_scene_mean=100 * sm("ece"), ece_pooled=100 * ece_pooled,
                nll_scene_mean=sm("nll"), nll_pooled=w("nll"),
                brier_scene_mean=100 * sm("brier"), brier_pooled=100 * w("brier"),
                acc_scene_mean=100 * sm("acc"), acc_pooled=100 * w("acc"),
                n_pixels=int(n.sum()), bins=bins)
    cal["units"] = "ECE, Brier, Acc in points (x100); NLL in nats"
    data["calibration"] = cal

    # ---- R2: a calibration difference holds only under both aggregations and in x/N
    r2 = []
    for d in DATASETS:
        for a_row, b in (("ours_P2", "averaging"), ("ours_P2", "ours_P0"), ("ours_P0", "averaging"),
                         ("ours_P2", "f3dgs"), ("ours_P2", legs[d]), ("ours_P2", "2d_features"),
                         ("ours_P0", "f3dgs"), ("ours_P0", legs[d]), ("ours_P0", "2d_features"),
                         ("averaging", "f3dgs"), ("averaging", legs[d])):
            for k in ("ece", "nll", "brier"):
                ca, cb = cal[d][a_row], cal[d][b]
                dm = cb[f"{k}_scene_mean"] - ca[f"{k}_scene_mean"]
                dp = cb[f"{k}_pooled"] - ca[f"{k}_pooled"]
                diff = signed(seg_values(M[d], a_row, k), seg_values(M[d], b, k), k)
                s = summarize(list(diff.values()), boot=False)
                n = s["n"]
                if dm > 0 and dp > 0 and 2 * s["wins"] > n:
                    v = "first lower under both, and in x/N"
                elif dm < 0 and dp < 0 and 2 * s["losses"] > n:
                    v = "baseline lower under both, and in x/N"
                else:
                    v = "no claim: depends on the aggregation or on x/N"
                r2.append(dict(dataset=d, first=a_row, baseline=b, metric=k,
                               diff_scene_mean=dm, diff_pooled=dp, wins=s["wins"], n=n,
                               sign_p=s["sign_p"], verdict=v))
    data["r2"] = dict(rule="R2: positive diff = first row lower (better); a difference is "
                           "claimed only if both aggregations agree and x/N > N/2",
                      checks=r2)

