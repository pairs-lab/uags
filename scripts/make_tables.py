"""
make_tables.py — LaTeX rows of the paper's Table I (tab:replica) from an eval_seg.py JSON, so
every number in the paper comes from a saved evaluation file (no hand copying).

    python3 scripts/make_tables.py tab1 <eval_test.json> [--variant all] > rows.tex

Rows and columns follow papers/main.tex (tab:replica): mean {\\scriptsize +- std} over the
scenes of the file, N printed in a comment. mIoU, Acc., ECE, AURC and AUSE in %, Brier x100,
NLL in nats. Variant "all" applies the coverage rule (uncovered pixels count as wrong).
AUSE_u = AUSE of the row's own uncertainty against the 0/1 error:
    NormLift rows  normlift_1-R / normlift_1-Cinter      CSS  css_var_top (its Eq. 10)
    ours           u_ale                                 2D / averaging: none ("--")
"""
from __future__ import annotations
import argparse
import json
import math

# (label in the paper, row name in the JSON, own-uncertainty signal or None, predictive shown)
TAB1 = [
    ("2D features, per frame", "2d_features", None, True),
    ("Averaging~\\cite{joseph2025gradbp}\\reimpl", "averaging", None, True),
    ("NormLift~\\cite{zang2026normlift}\\reimpl, $1-\\mathcal{R}$", "normlift", "normlift_1-R", False),
    ("NormLift\\reimpl, $1-C_{\\mathrm{inter}}$", "normlift", "normlift_1-Cinter", False),
    ("CSS (Dirichlet)~\\cite{wilson2025css}\\reimpl", "css", "css_var_top", True),
    ("Ours P0 (plug-in)", "ours_P0", "u_ale", True),
    ("Ours P1 (posterior mean)", "ours_P1", "u_ale", True),
    ("Ours P2 (adaptive $\\beta$)", "ours_P2", "u_ale", True),
]
COLS = [("miou", 100.0), ("acc", 100.0), ("ece", 100.0), ("nll", 1.0), ("brier", 100.0),
        ("aurc", 100.0)]


def body(path):
    d = json.load(open(path))
    return d["metrics"] if isinstance(d.get("metrics"), dict) else d


def cell(stat, scale, digits=1):
    if stat is None or stat.get("n", 0) == 0 or not math.isfinite(stat.get("mean", float("nan"))):
        return "--"
    m, s, n = stat["mean"] * scale, stat.get("std", float("nan")) * scale, stat["n"]
    if n < 2 or not math.isfinite(s):
        return f"{m:.{digits}f}"
    return f"{m:.{digits}f}{{\\scriptsize$\\,\\pm\\,${s:.{digits}f}}}"


def tab1(path, variant="all"):
    d = body(path)
    summ = d["summary"]
    ns = sorted({r[variant]["miou"]["n"] for r in summ.values()})
    lines = [f"% generated by scripts/make_tables.py tab1 {path} --variant {variant}; "
             f"scenes per row N = {ns}"]
    for label, row, sig, pred in TAB1:
        if row not in summ:
            lines.append(f"% {label}: row {row!r} not in {path}")
            continue
        m = summ[row][variant]
        if pred:
            cells = [cell(m.get(k), sc, 2 if k == "nll" else 1) for k, sc in COLS]
        else:
            cells = ["\\multicolumn{6}{c}{same predictive as averaging}"]
        ause = cell(m["ause"].get(sig), 100.0) if sig else "--"
        ov = "$\\times$" if row == "css" else "\\checkmark"
        lines.append(f"{label} & {ov} & " + " & ".join(cells) + f" & {ause}\\\\")
    return "\n".join(lines)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("table", choices=["tab1"])
    ap.add_argument("path")
    ap.add_argument("--variant", default="all", choices=["all", "covered"])
    a = ap.parse_args()
    print(tab1(a.path, a.variant))


if __name__ == "__main__":
    main()
