V2_COLS = ("miou", "acc", "ece", "nll", "brier", "aurc")


def v2_order(p):
    """Candidates in the prereg's order: @ours_v2's list with @p1 / @p4 expanded, then the
    ablations."""
    out = []
    for c in p["choices"]["@ours_v2"]["rows"]:
        out += p["choices"][c]["rows"] if c.startswith("@") else [c]
    return out + list(p.get("ablations", []))


def saved_choice(path):
    if not path or not os.path.exists(path):
        return None
    d = json.load(open(path))
    m = d.get("metrics", d) if isinstance(d.get("metrics"), dict) else d
    if "selection" in m:
        return m["selection"]["chosen"]
    if "v2" in m:
        return m["v2"]["chosen"]
    return None


def v2grid(args, argv):
    import make_tables as MT
    data, tex = header(args, argv)
    tests = {"replica": args.replica, "scannet": args.scannet}
    pre = dict(zip(DATASETS, args.prereg))
    data["datasets"] = {}
    for d in DATASETS:
        p = MT.load_prereg(pre[d])
        val = os.path.join(os.path.dirname(tests[d]), "eval_val.json")
        sel = os.path.join(os.path.dirname(tests[d]), "selection_val.json")
        vb = MT.body(val)
        chosen = {k: MT.choose_v2(vb, k, p)[0] for k in MT.V2_KEYS}
        saved = saved_choice(sel)
        if saved is not None and saved != chosen:
            raise SystemExit(f"{d}: the rule gives {chosen}, the selection record {saved}")
        tb = MT.body(tests[d])
        rows = []
        for r in v2_order(p):
            s = tb["summary"][r]["all"]
            if r == chosen["@ours_v2"]:
                status = "selected"
            elif r in (chosen["@p1"], chosen["@p4"]):
                status = "not selected (best of its grid on validation)"
            elif r in p.get("ablations", []):
                status = "not selected (ablation)"
            else:
                status = "not selected"
            e = dict(row=r, status=status, val_nll_pooled=MT.pooled(vb, r, "nll", "all"))
            for c in V2_COLS:
                e[c] = dict(mean=SCALE[c] * s[c]["mean"], std=SCALE[c] * s[c]["std"], n=s[c]["n"])
            e["ause_u_ale"] = dict(mean=100 * s["ause"]["u_ale"]["mean"],
                                   std=100 * s["ause"]["u_ale"]["std"])
            rows.append(e)
        data["datasets"][d] = dict(test=source(tests[d]), val=source(val),
                                   selection=(source(sel) if os.path.exists(sel) else None),
                                   prereg=source(pre[d]), chosen=chosen,
                                   saved_selection_matches=saved is not None, rows=rows)
        b = tex.block(f"v2grid_{d}", f"{DLABEL[d]} test: every pre-registered v2 candidate "
                      "(order of the prereg). Cols: row | validation NLL (pooled, the selection "
                      "criterion) | test mIoU | Acc. | ECE | NLL | Brier | AURC (mean +- std; % "
                      "except NLL) | status")
        for i, e in enumerate(rows):
            k = f"datasets/{d}/rows/{i}"
            row(b, [Tex.cell(f"{k}/row", "tex"), Tex.cell(f"{k}/val_nll_pooled", ".4f")]
                + [mean_std_cell(f"{k}/{c}", ".2f" if c == "nll" else ".1f") for c in V2_COLS]
                + [Tex.cell(f"{k}/status", "s")])
    write_outputs(args, data, tex)


