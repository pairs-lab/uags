"""
quant_stats.py — CPU statistics behind the paper's quantitative claims, computed from the saved
result JSONs and logs only (no GPU, nothing is re-evaluated). The rules are those of
configs/quant_prereg.json (R0-R2 and the test family F1); every test split read here was
already seen, so every p-value is descriptive, and only a Holm-adjusted p < 0.05 within the
declared family F1 may be called significant.

    python3 scripts/quant_stats.py seg      Table I: F1 (paired sign tests over the 14 test
                                            scenes, Holm), per-dataset x/N, both calibration
                                            aggregations, per-scene appendix tables
    python3 scripts/quant_stats.py nor      NeRF-Object-Removal: measured per-view static rate
                                            r_static, per-object table, Table III per scene,
                                            common-set AP, paired comparisons (descriptive)
    python3 scripts/quant_stats.py views    uncertainty ranking: Replica views test (every M)
                                            and the full-map point (Replica, ScanNet)
    python3 scripts/quant_stats.py cost     ScanNet build time from the production logs
    python3 scripts/quant_stats.py betas    fitted P2 coefficients in the paper's symbols
    python3 scripts/quant_stats.py v2grid   every pre-registered v2 candidate on test

Every input has a default (the saved records under $RES = <repo>/../../data/uags_results, or
$UAGS_RESULTS), and --json / --tex default to docs/reports/2026-10-20-figures-video/logs/quant/
<subcommand>.{json,tex}.

Statistics (R1): the unit is the scene. One paired test everywhere: the exact two-sided sign
test, ties (difference exactly 0) dropped. Effect size: the median paired difference in the
metric's own unit (points = x100 for mIoU, ECE, Brier, AURC, AUSE; nats for NLL), signed so
that positive = ours (the first row) better. x/N = scenes where the first row is better, out of
all N scenes. Wilcoxon (seg, family F1 only) is a complete secondary column. The bootstrap CI
(20,000 scene resamples, seed 0) is of the MEAN paired difference, descriptive only.
Aggregation (R2): ECE as the mean over scenes and pooled over pixels from the stored 15-bin
reliability bins (sum_b C_b |conf_b - acc_b| / sum_b C_b with the bins summed over scenes);
NLL, Brier and accuracy as the scene mean and pixel-weighted by n_pixels. seg stops unless
each scene's ECE recomputed from its bins equals the stored ECE (every row, both variants).

Outputs. --json holds every number (first key "_command": the generating command, paths
abbreviated as $RES / $NORD / repo-relative). --tex holds LaTeX rows in blocks ("%% block:"),
its first line is "%% generated by: <command>". Every LaTeX cell is also recorded in the JSON
(latex.blocks[].rows[].cells[]: its text, the JSON keys of its numbers, a template and a
format), so tests/test_quant_stats.py traces each printed number to a JSON key. The rows hold
no paths or names (anonymity); paths appear only in %% comments.
"""
